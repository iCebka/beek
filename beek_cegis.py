"""Sequential Beek candidate-search orchestrator.

This orchestrator composes *existing* Beek modules. It does not implement Kivi,
SPIN, YAML rewriting, parsing or Z3, nor does it claim semantic constraint
learning. Initially, the search uses single-candidate blocking and rechecking.

A campaign MUST run sequentially: Kivi uses process-global state and shares
intermediate files. No source YAML or previously verified iteration is mutated.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Callable, Mapping
import json
import os
import re
import uuid
from time import perf_counter_ns
from beek_metrics import (timed_stage, seconds, count_learning_impact,
                          aggregate_campaign_metrics)

from beek_materialization import materialize_repair
from beek_repair_spec import load_repair_spec
from beek_verification_artifacts import verify_and_save
from beek_verification_result import create_verification_result, INPUT_NAMES


class BeekCampaignError(RuntimeError):
    """An invalid campaign input or unrecoverable orchestrator failure."""


def _write_json(path: Path, value: dict) -> None:
    """Write a recoverable checkpoint atomically."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    os.replace(temporary, path)


def _validated_candidate(candidate: Mapping, parameters: Mapping, blocked: list[dict]) -> dict:
    if not isinstance(candidate, dict) or set(candidate) != set(parameters):
        raise BeekCampaignError("Z3 candidate must assign exactly the declared repair parameters")
    for name, value in candidate.items():
        if type(value) is not int or value not in parameters[name]["domain"]:
            raise BeekCampaignError(f"Z3 returned an out-of-domain value for {name}: {value!r}")
    if dict(candidate) in blocked:
        raise BeekCampaignError("Z3 proposed a previously refuted candidate")
    return dict(candidate)


def run_beek_cegis(
    model: dict,
    repair_spec_path: str | Path,
    max_verified_candidates: int,
    *,
    input_files: Mapping[str, str | Path],
    kivi_root: str | Path,
    case: str,
    output_root: str | Path,
    build_model_fn: Callable,
    verify_fn: Callable,
    read_raw_trace_fn: Callable,
    parse_counterexample_fn: Callable,
    build_repair_problem_fn: Callable,
    synthesize_repair_fn: Callable,
    learn_constraints_fn: Callable | None = None,
    campaign_id: str | None = None,
    objective: str | None = "from_spec",
    collect_metrics: bool = True,
    metrics_max_exact_space: int = 100_000,
) -> dict:
    """Verify, synthesize, materialize and reverify up to N new candidates.

    Required main inputs:
      model: initial Kivi model already generated by build_kivi_model.
      repair_spec_path: declarative modifiable parameters, domains and YAML bindings.
      max_verified_candidates: maximum *new* Z3 candidates to pass to Kivi;
          the required initial-model verification does NOT consume this budget.

    objective: "from_spec" (default) keeps the YAML-declared objective;
        "min_changes_then_distance" forces optimization; None or "none"
        disables objective optimization while retaining domains, blockers,
        and learned constraints.

    Other keyword inputs are existing Beek context and functions, supplied
    explicitly to avoid copying notebook implementations or depending on globals.

    Outcomes: PASS, BUDGET_EXHAUSTED, UNSAT, UNKNOWN, INCOMPLETE, ERROR.
    UNSAT is relative only to the bounded parameter domains and any supplied
    learned constraints, not an unrestricted Kubernetes unsatisfiability claim.

    Returns a summary with history, blocked candidates, artifact directories,
    and final six YAML paths (on PASS). Writes campaign-summary.json after
    each significant stage. Input/configuration precondition errors raise.
    Runtime errors are recorded and returned as status ERROR.
    """
    campaign_started_ns = perf_counter_ns()
    if type(collect_metrics) is not bool:
        raise TypeError("collect_metrics must be a boolean")
    if type(metrics_max_exact_space) is not int or metrics_max_exact_space < 1:
        raise ValueError("metrics_max_exact_space must be a positive integer")
    if not isinstance(model, dict):
        raise TypeError("model must be the dictionary returned by build_kivi_model")
    if type(max_verified_candidates) is not int or max_verified_candidates < 0:
        raise ValueError("max_verified_candidates must be an integer >= 0")
    if not isinstance(case, str) or re.fullmatch(r"[A-Za-z0-9_-]+", case) is None:
        raise ValueError("case must consist of letters, numbers, '-' or '_'")
    if set(input_files) != set(INPUT_NAMES):
        raise ValueError(f"input_files requires exactly these keys: {INPUT_NAMES}")
    for name, value in {
        "build_model_fn": build_model_fn,
        "verify_fn": verify_fn,
        "read_raw_trace_fn": read_raw_trace_fn,
        "parse_counterexample_fn": parse_counterexample_fn,
        "build_repair_problem_fn": build_repair_problem_fn,
        "synthesize_repair_fn": synthesize_repair_fn,
    }.items():
        if not callable(value):
            raise TypeError(f"{name} must be callable")
    if learn_constraints_fn is not None and not callable(learn_constraints_fn):
        raise TypeError("learn_constraints_fn must be callable or None")
    if objective not in ("from_spec", "min_changes_then_distance", "none", None):
        raise ValueError(
            "objective must be 'from_spec', 'min_changes_then_distance', 'none', or None"
        )

    current_inputs = {key: Path(input_files[key]).resolve(strict=True) for key in INPUT_NAMES}
    current_spec = Path(repair_spec_path).resolve(strict=True)
    root = Path(kivi_root).resolve(strict=True)
    # Fail before launching SPIN if a parameter in the YAML does not correspond
    # to the supplied initial model or falls outside its declared domain.
    initial_repair_spec = load_repair_spec(current_spec, current_inputs, model)
    resolved_objective = (
        initial_repair_spec["objective"] if objective == "from_spec"
        else "none" if objective is None else objective
    )

    if campaign_id is None:
        campaign_id = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ") + "_" + uuid.uuid4().hex[:8]
    if not isinstance(campaign_id, str) or re.fullmatch(r"[A-Za-z0-9_-]+", campaign_id) is None:
        raise ValueError("campaign_id must contain only letters, numbers, '-' or '_'")
    campaign_dir = Path(output_root).expanduser().resolve() / case / campaign_id
    campaign_dir.mkdir(parents=True, exist_ok=False)
    summary_path = campaign_dir / "campaign-summary.json"

    summary = {
        "schema": "beek.cegis-campaign.v1",
        "campaign_id": campaign_id,
        "case": case,
        "status": "RUNNING",
        "reason": None,
        "max_verified_candidates": max_verified_candidates,
        "objective": resolved_objective,
        "objective_source": "repair_spec" if objective == "from_spec" else "argument",
        "collect_metrics": collect_metrics,
        "metrics_max_exact_space": metrics_max_exact_space,
        "verified_candidates": 0,
        "total_verifications": 0,
        "blocked_candidates": [],
        "learned_constraints": [],
        "history": [],
        "verified_candidate": None,
        "final_input_files": None,
        "last_verification_result_path": None,
        "campaign_dir": str(campaign_dir),
        "summary_path": str(summary_path),
    }
    _write_json(summary_path, summary)

    current_model = model
    baseline_values = None
    parent_run_id = None
    blocked_candidates: list[dict] = []
    learned_constraints: list[dict] = []
    seen_constraints: set[str] = set()
    stage = "initialization"
    metrics_records: list[dict] = []

    try:
        for iteration in range(max_verified_candidates + 1):
            iteration_start_ns = perf_counter_ns()
            iteration_metrics = {
                "schema": "beek.iteration-metrics.v1",
                "iteration": iteration,
                "verification_status": None,
                "timings_s": {},
                "reasoning": {},
                "search_space": {},
                "z3": {"check_calls": 0},
                "subprocess_wall_time_s_by_stage": {},
                "warnings": [],
            }
            if collect_metrics:
                metrics_records.append(iteration_metrics)
            try:
                run_dir = campaign_dir / f"iteration-{iteration:03d}"
                verification_dir = run_dir / "verification"
                case_id = f"beek_{case.lower()}_{campaign_id}_i{iteration:03d}"
                stage = f"verification {iteration}"
                if iteration:
                    summary["verified_candidates"] += 1
                summary["total_verifications"] += 1
                _write_json(summary_path, summary)

                with timed_stage(iteration_metrics["timings_s"], "verification_and_artifacts", enabled=collect_metrics):
                    _verifier, artifacts = verify_and_save(
                        current_model,
                        root,
                        verification_dir,
                        verify_fn=verify_fn,
                        case_id=case_id,
                    )
                stage = f"verification-result {iteration}"
                with timed_stage(iteration_metrics["timings_s"], "verification_result", enabled=collect_metrics):
                    verification_result, result_path = create_verification_result(
                        model=current_model,
                        artifacts=artifacts,
                        input_files=current_inputs,
                        repair_spec_path=current_spec,
                        case=case,
                        iteration=iteration,
                        original_values=baseline_values,
                        parent_run_id=parent_run_id,
                    )
                if collect_metrics:
                    verification_metadata_path = verification_dir / "verification.json"
                    if verification_metadata_path.is_file():
                        try:
                            verification_metadata = json.loads(verification_metadata_path.read_text(encoding="utf-8"))
                            internal_times = verification_metadata.get("metrics", {})
                            iteration_metrics["verification_internal"] = internal_times
                            iteration_metrics["subprocess_wall_time_s_by_stage"] = internal_times.get(
                                "subprocess_wall_time_s_by_stage", {})
                        except (OSError, ValueError) as exc:
                            iteration_metrics["warnings"].append(
                                f"Could not read verification metrics: {type(exc).__name__}: {exc}")
                status = verification_result["verification"]["status"]
                iteration_metrics["verification_status"] = status
                parameters = verification_result["repair_parameters"]
                if baseline_values is None:
                    baseline_values = {name: entry["original"] for name, entry in parameters.items()}
                current_values = {name: entry["current"] for name, entry in parameters.items()}
                parent_run_id = verification_result["run"]["id"]
                history_entry = {
                    "iteration": iteration,
                    "candidate": current_values,
                    "metrics_path": str(run_dir / "metrics.json") if collect_metrics else None,
                    "verification_status": status,
                    "violated_intents": verification_result["verification"]["violated_intents"],
                    "verification_result_path": str(result_path),
                    "raw_trail_path": str(verification_result["artifacts"]["raw_trail"]),
                    "input_files": {
                        name: verification_result["inputs"][name]["snapshot_path"]
                        for name in INPUT_NAMES
                    },
                    "proposed_next_candidate": None,
                }
                summary["history"].append(history_entry)
                summary["last_verification_result_path"] = str(result_path)
                _write_json(summary_path, summary)

                if status == "PASS":
                    summary["status"] = "PASS"
                    summary["reason"] = "The candidate passed Kivi/SPIN verification within the model"
                    summary["verified_candidate"] = current_values
                    summary["final_input_files"] = dict(history_entry["input_files"])
                    break
                if status in ("INCOMPLETE", "ERROR"):
                    summary["status"] = status
                    summary["reason"] = verification_result["verification"].get("reason")
                    break
                if status != "VIOLATION":
                    raise BeekCampaignError(f"Unexpected verification status: {status!r}")

                # Only a confirmed violation may enter the blocked history.
                stage = f"parse counterexample {iteration}"
                with timed_stage(iteration_metrics["timings_s"], "counterexample_parsing", enabled=collect_metrics):
                    raw_text = read_raw_trace_fn(verification_result["artifacts"]["raw_trail"])
                    counterexample = parse_counterexample_fn(raw_text)
                if not isinstance(counterexample, dict) or not counterexample.get("violated_intents"):
                    raise BeekCampaignError("The verified violation has no parseable violated intent")
                if "unclassified" in counterexample["violated_intents"]:
                    raise BeekCampaignError("The counterexample intent could not be classified")
                _write_json(verification_dir / "counterexample.parsed.json", counterexample)

                stage = f"build repair problem {iteration}"
                solver_parameters = {
                    name: {
                        "original": info["original"],
                        "current": info["current"],
                        "domain": info["domain"],
                    }
                    for name, info in parameters.items()
                }
                constraints_before_learning = list(learned_constraints)
                if learn_constraints_fn is not None:
                    with timed_stage(iteration_metrics["timings_s"], "reasoning", enabled=collect_metrics):
                        newly_learned = learn_constraints_fn(counterexample, current_model, solver_parameters)
                    if newly_learned is None:
                        newly_learned = []
                    if not isinstance(newly_learned, (tuple, list)):
                        raise BeekCampaignError("learn_constraints_fn must return a list of constraint dictionaries")
                    for constraint in newly_learned:
                        key = json.dumps(constraint, sort_keys=True)
                        if key not in seen_constraints:
                            seen_constraints.add(key)
                            learned_constraints.append(constraint)
                    if collect_metrics:
                        reported = getattr(newly_learned, "reasoning_metrics", {})
                        iteration_metrics["reasoning"] = {
                            **(reported if isinstance(reported, dict) else {}),
                            "constraints_generated": len(newly_learned),
                            "constraints_accepted": len(learned_constraints) - len(constraints_before_learning),
                            "constraints_unique_total": len(learned_constraints),
                        }
                        _write_json(verification_dir / "reasoning.json", iteration_metrics["reasoning"])
                with timed_stage(iteration_metrics["timings_s"], "repair_problem", enabled=collect_metrics):
                    problem = build_repair_problem_fn(
                        counterexample,
                        solver_parameters,
                        constraints=learned_constraints,
                        blocked_candidates=blocked_candidates,
                        objective=resolved_objective,
                    )
                blocked_candidates = list(problem["blocked_candidates"])
                if collect_metrics:
                    with timed_stage(iteration_metrics["timings_s"], "search_space_count", enabled=True):
                        try:
                            iteration_metrics["search_space"] = count_learning_impact(
                                solver_parameters, blocked_candidates, constraints_before_learning,
                                learned_constraints, max_exact_space=metrics_max_exact_space)
                        except Exception as exc:
                            iteration_metrics["search_space"] = {
                                "status": "UNAVAILABLE",
                                "reason": f"{type(exc).__name__}: {exc}",
                            }
                if current_values not in blocked_candidates:
                    raise BeekCampaignError("Repair problem did not block the just-refuted candidate")
                summary["blocked_candidates"] = blocked_candidates
                summary["learned_constraints"] = learned_constraints
                _write_json(verification_dir / "repair-problem.json", problem)
                _write_json(summary_path, summary)

                if iteration == max_verified_candidates:
                    summary["status"] = "BUDGET_EXHAUSTED"
                    summary["reason"] = "Reached the maximum number of newly verified repair candidates"
                    break

                stage = f"Z3 synthesis {iteration}"
                with timed_stage(iteration_metrics["timings_s"], "synthesis", enabled=collect_metrics):
                    synthesis = synthesize_repair_fn(problem)
                if collect_metrics:
                    iteration_metrics["z3"] = {
                        "check_calls": synthesis.get("metrics", {}).get("check_calls", 1)
                        if isinstance(synthesis, dict) else 1,
                        "status": synthesis.get("status") if isinstance(synthesis, dict) else None,
                        "metrics": synthesis.get("metrics", {}) if isinstance(synthesis, dict) else {},
                    }
                if not isinstance(synthesis, dict):
                    raise BeekCampaignError("synthesize_repair_fn must return a result dictionary")
                _write_json(verification_dir / "synthesis.json", synthesis)
                synth_status = synthesis.get("status")
                if synth_status == "UNSAT":
                    summary["status"] = "UNSAT"
                    summary["reason"] = "No unblocked assignment satisfies the bounded solver problem"
                    break
                if synth_status == "UNKNOWN":
                    summary["status"] = "UNKNOWN"
                    summary["reason"] = synthesis.get("reason", "Z3 returned UNKNOWN")
                    break
                if synth_status != "SAT":
                    raise BeekCampaignError(f"Unexpected synthesis status: {synth_status!r}")

                candidate = _validated_candidate(synthesis.get("candidate"), solver_parameters, blocked_candidates)
                history_entry["proposed_next_candidate"] = candidate
                _write_json(summary_path, summary)

                stage = f"materialization {iteration + 1}"
                next_dir = campaign_dir / f"iteration-{iteration + 1:03d}" / "inputs"
                with timed_stage(iteration_metrics["timings_s"], "materialization", enabled=collect_metrics):
                    next_input_files, materialization = materialize_repair(
                        verification_result=verification_result,
                        candidate=candidate,
                        output_dir=next_dir,
                    )
                history_entry["materialization_path"] = materialization["materialization_path"]

                stage = f"reconstruction {iteration + 1}"
                with timed_stage(iteration_metrics["timings_s"], "reconstruction_and_validation", enabled=collect_metrics):
                    next_model = build_model_fn(
                        next_input_files["cluster"],
                        next_input_files["deployment"],
                        next_input_files["initial_state"],
                        next_input_files["hpa"],
                        next_input_files["intents"],
                        next_input_files["events"],
                    )
                    # Ensure candidate YAMLs and reconstructed model agree before SPIN.
                    load_repair_spec(
                        materialization["repair_spec_path"],
                        next_input_files,
                        next_model,
                        original_values=baseline_values,
                    )
                current_model = next_model
                current_inputs = next_input_files
                current_spec = Path(materialization["repair_spec_path"])
                _write_json(summary_path, summary)
            finally:
                if collect_metrics:
                    iteration_metrics["timings_s"]["iteration_total"] = seconds(perf_counter_ns() - iteration_start_ns)
                    iteration_dir = campaign_dir / f"iteration-{iteration:03d}"
                    _write_json(iteration_dir / "metrics.json", iteration_metrics)
        else:
            raise BeekCampaignError("Internal iteration limit not respected")
    except Exception as exc:
        summary["status"] = "ERROR"
        summary["reason"] = f"{stage}: {type(exc).__name__}: {exc}"
        summary["error_type"] = type(exc).__name__
    finally:
        if collect_metrics:
            summary["metrics"] = aggregate_campaign_metrics(
                metrics_records, seconds(perf_counter_ns() - campaign_started_ns))
            summary["metrics"]["iteration_metrics_paths"] = [
                str(campaign_dir / f"iteration-{record['iteration']:03d}" / "metrics.json")
                for record in metrics_records
            ]
        _write_json(summary_path, summary)

    return summary
